class Solution {
    public long countCommas(long n) {
        if(n < 1000) {
            return 0;
        }
        if(n <= 999999) { // 10 ^ 6
            return n - 999;
        }
        else if(n <= 999999999L){ // 10 ^ 9
            return (999999 - 999) + (2 *(n - 999999));
        }
        else if(n <= 999999999999L) {
            return (999999 - 999) + (2 *(999999999L - 999999)) + (3 * (n - 999999999L));
        }
        else if(n <= 999999999999999L) {
            return (999999 - 999) + 2 * (999999999 - 999999)
                 + 3 * (999999999999L - 999999999)
                 + 4 * (n - 999999999999L);
        }
        return (999999 - 999)
            + 2 * (999999999 - 999999)
            + 3 * (999999999999L - 999999999)
            + 4 * (999999999999999L - 999999999999L)
            + 5 * (n - 999999999999999L);
    }
}